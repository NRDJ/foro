-- =====================================================================
-- Sistema de Foros en Linea - Tablas y datos iniciales
-- Ejecutar conectado como FORO (SQL Developer o SQL*Plus). Se puede repetir:
-- borra las tablas y las vuelve a crear con los datos de prueba.
--
-- Propiedad de las tablas:
--   ms-usuarios -> USUARIOS
--   ms-foros    -> CATEGORIAS, TEMAS, COMENTARIOS
-- TEMAS y COMENTARIOS guardan AUTOR_ID y AUTOR_USERNAME sin clave foranea hacia
-- USUARIOS: cada microservicio es dueno de sus datos, y una publicacion se conserva
-- aunque su autor elimine su cuenta.
--
-- Clave de todos los usuarios de prueba: Foro2026!
-- =====================================================================
SET DEFINE OFF

BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('COMENTARIOS', 'TEMAS', 'CATEGORIAS', 'USUARIOS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

CREATE TABLE USUARIOS (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    USERNAME            VARCHAR2(50 CHAR)  NOT NULL,
    EMAIL               VARCHAR2(120 CHAR) NOT NULL,
    PASSWORD_HASH       VARCHAR2(100 CHAR) NOT NULL,
    NOMBRE              VARCHAR2(100 CHAR) NOT NULL,
    ROL                 VARCHAR2(20 CHAR)  NOT NULL,
    FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_USUARIOS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ROL CHECK (ROL IN ('ADMIN', 'USUARIO'))
);

CREATE TABLE CATEGORIAS (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    NOMBRE      VARCHAR2(60 CHAR)  NOT NULL,
    DESCRIPCION VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT UK_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE TEMAS (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    TITULO              VARCHAR2(150 CHAR)  NOT NULL,
    CONTENIDO           VARCHAR2(1000 CHAR) NOT NULL,
    CATEGORIA_ID        NUMBER(19)          NOT NULL,
    AUTOR_ID            NUMBER(19)          NOT NULL,
    AUTOR_USERNAME      VARCHAR2(50 CHAR)   NOT NULL,
    FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TEMAS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS (ID)
);
CREATE INDEX IX_TEMAS_CATEGORIA ON TEMAS (CATEGORIA_ID);
CREATE INDEX IX_TEMAS_AUTOR ON TEMAS (AUTOR_ID);

CREATE TABLE COMENTARIOS (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    CONTENIDO           VARCHAR2(1000 CHAR) NOT NULL,
    TEMA_ID             NUMBER(19)          NOT NULL,
    AUTOR_ID            NUMBER(19)          NOT NULL,
    AUTOR_USERNAME      VARCHAR2(50 CHAR)   NOT NULL,
    FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_COMENTARIOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMAS (ID) ON DELETE CASCADE
);
CREATE INDEX IX_COMENTARIOS_TEMA ON COMENTARIOS (TEMA_ID);

